"use client";

import {
  AlertTriangle,
  CheckCircle2,
  Clock,
  Download,
  FileSpreadsheet,
  FileText,
  Printer,
  Sparkles,
} from "lucide-react";
import { DICT, Lang } from "@/lib/i18n";

export interface BriefData {
  generatedAt: string;
  stats: {
    activeSurveys: number;
    avgTurnout: number;
    flaggedDrops: number;
    openIssues: number;
    overdueIssues: number;
    verifiedIssues: number;
  };
  drops: Array<{
    groupName: string;
    surveyTitle: string;
    dimension: string;
    previousScore: number;
    currentScore: number;
    delta: number;
  }>;
  latestSummaries: Array<{
    groupName: string;
    lecturerName: string;
    surveyTitle: string;
    responseRate: number;
    sampleSize: number;
    overallScore: number;
    summary: string;
    topNegativeThemes: Array<{ theme: string; count: number }>;
  }>;
  issues: Array<{
    id: string;
    title: string;
    groupName: string;
    category: string;
    severity: string;
    status: string;
    ownerRole: string;
    ownerName: string;
    dueDate: string;
    isOverdue: boolean;
  }>;
}

export function MeetingBriefClient({
  data,
  lang = "hy",
}: {
  data: BriefData;
  lang?: Lang;
}) {
  const t = DICT[lang];
  function buildMarkdown(): string {
    const lines: string[] = [
      `# Picsart Academy — Quality Sync Meeting Brief`,
      `_Generated by Pulse on ${new Date(data.generatedAt).toLocaleString()}_`,
      ``,
      `## Executive Snapshot`,
      `- **Active Surveys:** ${data.stats.activeSurveys}`,
      `- **Average Turnout:** ${data.stats.avgTurnout}%`,
      `- **Flagged Score Drops (>= 0.4 pts):** ${data.stats.flaggedDrops}`,
      `- **Open Issues:** ${data.stats.openIssues} (${data.stats.overdueIssues} overdue)`,
      `- **Verified Fixes:** ${data.stats.verifiedIssues}`,
      ``,
      `## Flagged Score Drops`,
    ];

    if (data.drops.length === 0) {
      lines.push(`- No major score drops detected across latest survey waves.`);
    } else {
      for (const d of data.drops) {
        lines.push(
          `- **${d.groupName} — ${d.dimension}**: ${d.previousScore.toFixed(1)} → ${d.currentScore.toFixed(1)} (${d.delta.toFixed(2)} pts in _${d.surveyTitle}_)`
        );
      }
    }

    lines.push(``, `## Cohort AI Summaries`);
    for (const s of data.latestSummaries) {
      lines.push(
        `### ${s.groupName} (${s.lecturerName}) — ${s.overallScore.toFixed(2)}/5 (n=${s.sampleSize}, ${s.responseRate}%)`,
        s.summary
      );
      if (s.topNegativeThemes.length > 0) {
        lines.push(
          `- Key concerns: ${s.topNegativeThemes
            .map((t) => `${t.theme} (${t.count})`)
            .join(", ")}`
        );
      }
      lines.push(``);
    }

    lines.push(`## Tracked Issues by Status`);
    for (const i of data.issues) {
      lines.push(
        `- [${i.status}${i.isOverdue ? " · OVERDUE" : ""}] **${i.title}** (${i.groupName} · ${i.ownerName} · Due ${new Date(i.dueDate).toLocaleDateString()})`
      );
    }

    return lines.join("\n");
  }

  function downloadFile(content: string, filename: string, mime: string) {
    const blob = new Blob([content], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  }

  function handleDownloadMarkdown() {
    const md = buildMarkdown();
    const date = new Date().toISOString().slice(0, 10);
    downloadFile(md, `pulse-meeting-brief-${date}.md`, "text/markdown;charset=utf-8");
  }

  function handleDownloadCsv() {
    const header = [
      "Group",
      "Title",
      "Category",
      "Severity",
      "Status",
      "Owner Role",
      "Owner Name",
      "Due Date",
      "Overdue",
    ];
    const rows = data.issues.map((i) =>
      [
        i.groupName,
        `"${i.title.replace(/"/g, '""')}"`,
        i.category,
        i.severity,
        i.status,
        i.ownerRole,
        `"${i.ownerName.replace(/"/g, '""')}"`,
        new Date(i.dueDate).toISOString().slice(0, 10),
        i.isOverdue ? "YES" : "NO",
      ].join(",")
    );
    const csv = [header.join(","), ...rows].join("\n");
    const date = new Date().toISOString().slice(0, 10);
    downloadFile(csv, `pulse-issues-${date}.csv`, "text/csv;charset=utf-8");
  }

  return (
    <div className="space-y-6">
      {/* Header & Export Actions */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3 print:hidden">
        <div>
          <h1 className="text-3xl font-extrabold tracking-tight text-slate-950 dark:text-white">
            {t.reports.title}
          </h1>
          <p className="text-sm font-medium text-slate-600 dark:text-slate-400 mt-1">
            {t.reports.subtitle}
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <button
            onClick={handleDownloadCsv}
            className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-white dark:bg-[#1e2229] border border-slate-300 dark:border-white/[0.12] text-slate-800 dark:text-white text-xs font-bold hover:border-[#00e5cc] cursor-pointer"
          >
            <FileSpreadsheet className="w-4 h-4 text-teal-600 dark:text-[#00f0d8]" />
            CSV
          </button>
          <button
            onClick={handleDownloadMarkdown}
            className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-[#ffe600] hover:bg-[#f5d800] text-slate-950 text-xs font-extrabold cursor-pointer"
          >
            <Download className="w-4 h-4" />
            Markdown (.md)
          </button>
          <button
            onClick={() => window.print()}
            className="inline-flex items-center gap-1.5 px-4 py-2 rounded-xl bg-[#e000df] hover:bg-[#c400c3] text-white text-xs font-extrabold shadow-[0_0_22px_rgba(224,0,223,0.34)] cursor-pointer"
          >
            <Printer className="w-4 h-4" />
            {t.reports.printPdf}
          </button>
        </div>
      </div>

      {/* Printable Report Sheet */}
      <div className="bento-card p-6 md:p-8 space-y-8 print:border-0 print:shadow-none print:p-0">
        {/* Report Title */}
        <div className="border-b border-slate-200 dark:border-white/[0.08] pb-4 flex items-start justify-between gap-4">
          <div>
            <div className="text-xs font-extrabold uppercase tracking-wider text-teal-700 dark:text-[#00f0d8] flex items-center gap-1.5">
              <FileText className="w-3.5 h-3.5" />
              {t.reports.reportBadge}
            </div>
            <h2 className="text-xl font-extrabold text-slate-950 dark:text-white mt-1">
              {t.reports.reportHeading}
            </h2>
          </div>
          <div className="text-right text-xs text-slate-500 dark:text-slate-400">
            <div>{t.reports.generated}</div>
            <div className="font-bold text-slate-900 dark:text-white">
              {new Date(data.generatedAt).toLocaleDateString()}
            </div>
          </div>
        </div>

        {/* KPI Strip */}
        <div className="grid grid-cols-2 sm:grid-cols-5 gap-3">
          <StatBox label={t.dashboard.kpiActive} value={String(data.stats.activeSurveys)} />
          <StatBox label={t.dashboard.kpiTurnout} value={`${data.stats.avgTurnout}%`} />
          <StatBox
            label={t.dashboard.kpiDrops}
            value={String(data.stats.flaggedDrops)}
            accent={data.stats.flaggedDrops > 0 ? "rose" : "emerald"}
          />
          <StatBox
            label={`${t.dashboard.kpiOpen} / ${t.dashboard.kpiOverdue}`}
            value={`${data.stats.openIssues} / ${data.stats.overdueIssues}`}
            accent={data.stats.overdueIssues > 0 ? "rose" : "slate"}
          />
          <StatBox
            label={t.dashboard.kpiVerified}
            value={String(data.stats.verifiedIssues)}
            accent="emerald"
          />
        </div>

        {/* Section 1: Score Drops */}
        <section className="space-y-3">
          <h3 className="text-sm font-extrabold uppercase tracking-wider text-primary flex items-center gap-1.5">
            <AlertTriangle className="w-4 h-4 text-rose-500" />
            {t.reports.sec1}
          </h3>
          {data.drops.length === 0 ? (
            <p className="text-sm font-semibold text-cyan-accent bento-inner px-4 py-3">
              {t.reports.noDrops}
            </p>
          ) : (
            <div className="space-y-2">
              {data.drops.map((d, idx) => (
                <div
                  key={idx}
                  className="flex items-center justify-between bento-warn px-4 py-3 text-sm"
                >
                  <div>
                    <strong className="text-primary">
                      {d.groupName} — {d.dimension}
                    </strong>{" "}
                    <span className="text-muted">({d.surveyTitle})</span>
                  </div>
                  <div className="font-extrabold text-rose-500">
                    {d.previousScore.toFixed(1)} → {d.currentScore.toFixed(1)} (
                    {d.delta.toFixed(2)})
                  </div>
                </div>
              ))}
            </div>
          )}
        </section>

        {/* Section 2: Cohort AI Summaries */}
        <section className="space-y-3">
          <h3 className="text-sm font-extrabold uppercase tracking-wider text-primary flex items-center gap-1.5">
            <Sparkles className="w-4 h-4 text-[#e000df]" />
            {t.reports.sec2}
          </h3>
          <div className="space-y-3">
            {data.latestSummaries.map((s, idx) => (
              <div
                key={idx}
                className="bento-inner p-4 space-y-2"
              >
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <div>
                    <span className="font-extrabold text-primary">
                      {s.groupName}
                    </span>
                    <span className="text-xs text-muted ml-2">
                      {s.lecturerName} · {s.surveyTitle}
                    </span>
                  </div>
                  <div className="text-xs font-extrabold text-cyan-accent">
                    {s.overallScore.toFixed(2)}/5 · n={s.sampleSize} ({s.responseRate}%)
                  </div>
                </div>
                <p className="text-sm font-medium text-primary leading-relaxed">
                  {s.summary}
                </p>
                {s.topNegativeThemes.length > 0 && (
                  <div className="flex flex-wrap gap-1.5 pt-1">
                    {s.topNegativeThemes.map((th, tIdx) => (
                      <span
                        key={tIdx}
                        className="text-[11px] font-extrabold px-2.5 py-0.5 rounded-full bg-rose-500/15 text-rose-500"
                      >
                        {th.theme} ({th.count})
                      </span>
                    ))}
                  </div>
                )}
              </div>
            ))}
          </div>
        </section>

        {/* Section 3: Owned Action Items */}
        <section className="space-y-3">
          <h3 className="text-sm font-extrabold uppercase tracking-wider text-primary flex items-center gap-1.5">
            <CheckCircle2 className="w-4 h-4 text-cyan-accent" />
            {t.reports.sec3}
          </h3>
          <div className="overflow-x-auto">
            <table className="w-full text-xs text-left">
              <thead>
                <tr className="border-b border-[var(--border)] text-muted uppercase font-bold">
                  <th className="py-2 pr-3">{t.dashboard.colIssue}</th>
                  <th className="py-2 px-2">{t.dashboard.colGroup}</th>
                  <th className="py-2 px-2">{t.dashboard.colOwner}</th>
                  <th className="py-2 px-2">{t.dashboard.colDue}</th>
                  <th className="py-2 pl-2">{t.dashboard.colStatus}</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {data.issues.map((i) => (
                  <tr key={i.id}>
                    <td className="py-2.5 pr-3 font-bold text-primary">
                      {i.title}
                    </td>
                    <td className="py-2.5 px-2 font-bold text-cyan-accent">{i.groupName}</td>
                    <td className="py-2.5 px-2 text-muted">{i.ownerName}</td>
                    <td className="py-2.5 px-2 whitespace-nowrap">
                      <span
                        className={
                          i.isOverdue
                            ? "text-rose-500 font-extrabold inline-flex items-center gap-1"
                            : "text-muted inline-flex items-center gap-1"
                        }
                      >
                        <Clock className="w-3 h-3" />
                        {new Date(i.dueDate).toLocaleDateString()}
                      </span>
                    </td>
                    <td className="py-2.5 pl-2 font-extrabold text-primary">
                      {t.status[i.status as keyof typeof t.status] ?? i.status}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </section>
      </div>
    </div>
  );
}

function StatBox({
  label,
  value,
  accent = "slate",
}: {
  label: string;
  value: string;
  accent?: "slate" | "rose" | "emerald";
}) {
  const color =
    accent === "rose"
      ? "text-rose-600"
      : accent === "emerald"
        ? "text-emerald-600"
        : "text-slate-900";
  return (
    <div className="rounded-xl border border-slate-200 bg-slate-50/70 p-3">
      <div className="text-[11px] text-slate-500 font-medium">{label}</div>
      <div className={`text-xl font-bold mt-0.5 ${color}`}>{value}</div>
    </div>
  );
}
