"use client";

import {
  AlertTriangle,
  CheckCircle2,
  Clock,
  Download,
  FileSpreadsheet,
  FileText,
  Printer,
  Sparkles,
} from "lucide-react";

export interface BriefData {
  generatedAt: string;
  stats: {
    activeSurveys: number;
    avgTurnout: number;
    flaggedDrops: number;
    openIssues: number;
    overdueIssues: number;
    verifiedIssues: number;
  };
  drops: Array<{
    groupName: string;
    surveyTitle: string;
    dimension: string;
    previousScore: number;
    currentScore: number;
    delta: number;
  }>;
  latestSummaries: Array<{
    groupName: string;
    lecturerName: string;
    surveyTitle: string;
    responseRate: number;
    sampleSize: number;
    overallScore: number;
    summary: string;
    topNegativeThemes: Array<{ theme: string; count: number }>;
  }>;
  issues: Array<{
    id: string;
    title: string;
    groupName: string;
    category: string;
    severity: string;
    status: string;
    ownerRole: string;
    ownerName: string;
    dueDate: string;
    isOverdue: boolean;
  }>;
}

export function MeetingBriefClient({ data }: { data: BriefData }) {
  function buildMarkdown(): string {
    const lines: string[] = [
      `# Picsart Academy — Quality Sync Meeting Brief`,
      `_Generated by Pulse on ${new Date(data.generatedAt).toLocaleString()}_`,
      ``,
      `## Executive Snapshot`,
      `- **Active Surveys:** ${data.stats.activeSurveys}`,
      `- **Average Turnout:** ${data.stats.avgTurnout}%`,
      `- **Flagged Score Drops (>= 0.4 pts):** ${data.stats.flaggedDrops}`,
      `- **Open Issues:** ${data.stats.openIssues} (${data.stats.overdueIssues} overdue)`,
      `- **Verified Fixes:** ${data.stats.verifiedIssues}`,
      ``,
      `## Flagged Score Drops`,
    ];

    if (data.drops.length === 0) {
      lines.push(`- No major score drops detected across latest survey waves.`);
    } else {
      for (const d of data.drops) {
        lines.push(
          `- **${d.groupName} — ${d.dimension}**: ${d.previousScore.toFixed(1)} → ${d.currentScore.toFixed(1)} (${d.delta.toFixed(2)} pts in _${d.surveyTitle}_)`
        );
      }
    }

    lines.push(``, `## Cohort AI Summaries`);
    for (const s of data.latestSummaries) {
      lines.push(
        `### ${s.groupName} (${s.lecturerName}) — ${s.overallScore.toFixed(2)}/5 (n=${s.sampleSize}, ${s.responseRate}%)`,
        s.summary
      );
      if (s.topNegativeThemes.length > 0) {
        lines.push(
          `- Key concerns: ${s.topNegativeThemes
            .map((t) => `${t.theme} (${t.count})`)
            .join(", ")}`
        );
      }
      lines.push(``);
    }

    lines.push(`## Tracked Issues by Status`);
    for (const i of data.issues) {
      lines.push(
        `- [${i.status}${i.isOverdue ? " · OVERDUE" : ""}] **${i.title}** (${i.groupName} · ${i.ownerName} · Due ${new Date(i.dueDate).toLocaleDateString()})`
      );
    }

    return lines.join("\n");
  }

  function downloadFile(content: string, filename: string, mime: string) {
    const blob = new Blob([content], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  }

  function handleDownloadMarkdown() {
    const md = buildMarkdown();
    const date = new Date().toISOString().slice(0, 10);
    downloadFile(md, `pulse-meeting-brief-${date}.md`, "text/markdown;charset=utf-8");
  }

  function handleDownloadCsv() {
    const header = [
      "Group",
      "Title",
      "Category",
      "Severity",
      "Status",
      "Owner Role",
      "Owner Name",
      "Due Date",
      "Overdue",
    ];
    const rows = data.issues.map((i) =>
      [
        i.groupName,
        `"${i.title.replace(/"/g, '""')}"`,
        i.category,
        i.severity,
        i.status,
        i.ownerRole,
        `"${i.ownerName.replace(/"/g, '""')}"`,
        new Date(i.dueDate).toISOString().slice(0, 10),
        i.isOverdue ? "YES" : "NO",
      ].join(",")
    );
    const csv = [header.join(","), ...rows].join("\n");
    const date = new Date().toISOString().slice(0, 10);
    downloadFile(csv, `pulse-issues-${date}.csv`, "text/csv;charset=utf-8");
  }

  return (
    <div className="space-y-6">
      {/* Header & Export Actions */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3 print:hidden">
        <div>
          <h1 className="text-2xl font-bold tracking-tight text-slate-900">
            Leadership Meeting Brief
          </h1>
          <p className="text-sm text-slate-500 mt-0.5">
            Ready-to-present quality summary for the Edu Lead, Admin Lead, and Director sync.
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <button
            onClick={handleDownloadCsv}
            className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg bg-white border border-slate-300 text-slate-700 text-xs font-medium hover:bg-slate-50 cursor-pointer"
          >
            <FileSpreadsheet className="w-4 h-4 text-emerald-600" />
            Issues CSV
          </button>
          <button
            onClick={handleDownloadMarkdown}
            className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg bg-white border border-slate-300 text-slate-700 text-xs font-medium hover:bg-slate-50 cursor-pointer"
          >
            <Download className="w-4 h-4 text-indigo-600" />
            Markdown (.md)
          </button>
          <button
            onClick={() => window.print()}
            className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-lg bg-indigo-600 text-white text-xs font-medium hover:bg-indigo-700 shadow-sm cursor-pointer"
          >
            <Printer className="w-4 h-4" />
            Print / Save PDF
          </button>
        </div>
      </div>

      {/* Printable Report Sheet */}
      <div className="bg-white rounded-2xl border border-slate-200 p-6 md:p-8 shadow-xs space-y-8 print:border-0 print:shadow-none print:p-0">
        {/* Report Title */}
        <div className="border-b border-slate-200 pb-4 flex items-start justify-between gap-4">
          <div>
            <div className="text-xs font-semibold uppercase tracking-wider text-indigo-600 flex items-center gap-1.5">
              <FileText className="w-3.5 h-3.5" />
              Picsart Academy · Pulse Quality Report
            </div>
            <h2 className="text-xl font-bold text-slate-900 mt-1">
              Academy Quality Sync Brief
            </h2>
          </div>
          <div className="text-right text-xs text-slate-500">
            <div>Generated</div>
            <div className="font-medium text-slate-800">
              {new Date(data.generatedAt).toLocaleDateString()}
            </div>
          </div>
        </div>

        {/* KPI Strip */}
        <div className="grid grid-cols-2 sm:grid-cols-5 gap-3">
          <StatBox label="Active Surveys" value={String(data.stats.activeSurveys)} />
          <StatBox label="Avg Turnout" value={`${data.stats.avgTurnout}%`} />
          <StatBox
            label="Flagged Drops"
            value={String(data.stats.flaggedDrops)}
            accent={data.stats.flaggedDrops > 0 ? "rose" : "emerald"}
          />
          <StatBox
            label="Open / Overdue"
            value={`${data.stats.openIssues} / ${data.stats.overdueIssues}`}
            accent={data.stats.overdueIssues > 0 ? "rose" : "slate"}
          />
          <StatBox
            label="Verified Fixes"
            value={String(data.stats.verifiedIssues)}
            accent="emerald"
          />
        </div>

        {/* Section 1: Score Drops */}
        <section className="space-y-3">
          <h3 className="text-sm font-bold uppercase tracking-wider text-slate-700 flex items-center gap-1.5">
            <AlertTriangle className="w-4 h-4 text-rose-500" />
            1. Priority Score Drops (≥ 0.4 pts)
          </h3>
          {data.drops.length === 0 ? (
            <p className="text-sm text-emerald-700 bg-emerald-50 border border-emerald-200 rounded-lg px-4 py-3">
              No score drops detected across the latest survey waves.
            </p>
          ) : (
            <div className="space-y-2">
              {data.drops.map((d, idx) => (
                <div
                  key={idx}
                  className="flex items-center justify-between bg-rose-50 border border-rose-200 rounded-lg px-4 py-3 text-sm"
                >
                  <div>
                    <strong className="text-slate-900">
                      {d.groupName} — {d.dimension}
                    </strong>{" "}
                    <span className="text-slate-600">({d.surveyTitle})</span>
                  </div>
                  <div className="font-semibold text-rose-700">
                    {d.previousScore.toFixed(1)} → {d.currentScore.toFixed(1)} (
                    {d.delta.toFixed(2)} pts)
                  </div>
                </div>
              ))}
            </div>
          )}
        </section>

        {/* Section 2: Cohort AI Summaries */}
        <section className="space-y-3">
          <h3 className="text-sm font-bold uppercase tracking-wider text-slate-700 flex items-center gap-1.5">
            <Sparkles className="w-4 h-4 text-indigo-500" />
            2. Cohort AI Summaries (Latest Wave)
          </h3>
          <div className="space-y-3">
            {data.latestSummaries.map((s, idx) => (
              <div
                key={idx}
                className="rounded-xl border border-slate-200 p-4 space-y-2"
              >
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <div>
                    <span className="font-semibold text-slate-900">
                      {s.groupName}
                    </span>
                    <span className="text-xs text-slate-500 ml-2">
                      {s.lecturerName} · {s.surveyTitle}
                    </span>
                  </div>
                  <div className="text-xs font-semibold text-slate-700">
                    {s.overallScore.toFixed(2)}/5 · n={s.sampleSize} ({s.responseRate}%)
                  </div>
                </div>
                <p className="text-sm text-slate-700 leading-relaxed">
                  {s.summary}
                </p>
                {s.topNegativeThemes.length > 0 && (
                  <div className="flex flex-wrap gap-1.5 pt-1">
                    {s.topNegativeThemes.map((t, tIdx) => (
                      <span
                        key={tIdx}
                        className="text-[11px] font-medium px-2 py-0.5 rounded-full bg-rose-100 text-rose-700"
                      >
                        {t.theme} ({t.count})
                      </span>
                    ))}
                  </div>
                )}
              </div>
            ))}
          </div>
        </section>

        {/* Section 3: Owned Action Items */}
        <section className="space-y-3">
          <h3 className="text-sm font-bold uppercase tracking-wider text-slate-700 flex items-center gap-1.5">
            <CheckCircle2 className="w-4 h-4 text-emerald-600" />
            3. Action Items &amp; Verification Tracker
          </h3>
          <div className="overflow-x-auto">
            <table className="w-full text-xs text-left">
              <thead>
                <tr className="border-b border-slate-200 text-slate-500 uppercase">
                  <th className="py-2 pr-3 font-medium">Issue</th>
                  <th className="py-2 px-2 font-medium">Group</th>
                  <th className="py-2 px-2 font-medium">Owner</th>
                  <th className="py-2 px-2 font-medium">Due</th>
                  <th className="py-2 pl-2 font-medium">Status</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {data.issues.map((i) => (
                  <tr key={i.id}>
                    <td className="py-2.5 pr-3 font-medium text-slate-900">
                      {i.title}
                    </td>
                    <td className="py-2.5 px-2 text-slate-600">{i.groupName}</td>
                    <td className="py-2.5 px-2 text-slate-600">{i.ownerName}</td>
                    <td className="py-2.5 px-2 whitespace-nowrap">
                      <span
                        className={
                          i.isOverdue
                            ? "text-rose-600 font-semibold inline-flex items-center gap-1"
                            : "text-slate-600 inline-flex items-center gap-1"
                        }
                      >
                        <Clock className="w-3 h-3" />
                        {new Date(i.dueDate).toLocaleDateString()}
                      </span>
                    </td>
                    <td className="py-2.5 pl-2 font-semibold text-slate-700">
                      {i.status}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </section>
      </div>
    </div>
  );
}

function StatBox({
  label,
  value,
  accent = "slate",
}: {
  label: string;
  value: string;
  accent?: "slate" | "rose" | "emerald";
}) {
  const color =
    accent === "rose"
      ? "text-rose-600"
      : accent === "emerald"
        ? "text-emerald-600"
        : "text-slate-900";
  return (
    <div className="rounded-xl border border-slate-200 bg-slate-50/70 p-3">
      <div className="text-[11px] text-slate-500 font-medium">{label}</div>
      <div className={`text-xl font-bold mt-0.5 ${color}`}>{value}</div>
    </div>
  );
}
